def labels_for(slug, lang):
    """取某语言下某工具的界面文案；未翻译的语言整体回落到英文（绝不回落中文）。"""
    table = LABELS.get(lang) or LABELS['en']
    got = table.get(slug)
    if got:
        return got
    return LABELS['en'].get(slug, {})
